def option_label(value,lang):
    v=str(value)
    if lang!='fa':
        return v
    if v in RESULT_FA:return RESULT_FA[v]
    if v in HEALTH_FA:return HEALTH_FA[v]
    if v in WEEKDAYS_FA:return WEEKDAYS_FA[v]
    if v in MISTAKE_FA:return MISTAKE_FA[v]
    if v in EVENT_FA:return EVENT_FA[v]
    if v in COMPONENT_FA:return COMPONENT_FA[v]
    return v


def localize_df(df,lang):
    if df is None or lang!='fa':
        return df
    try:
        out=df.copy() if isinstance(df,pd.DataFrame) else pd.DataFrame(df)
    except Exception:
        return df
    # Translate common categorical presentation values without mutating source data.
    for col in list(out.columns):
        if str(col) in ('Result','result_type','weekday','event_type','Component','direction','Type','report_type','health','current_stage','stage','status'):
            out[col]=out[col].map(lambda x:option_label(x,'fa') if pd.notna(x) else x)
    return out.rename(columns={c:COLUMN_FA.get(str(c),c) for c in out.columns})


